#!/usr/bin/env python3
"""Merge benchmark CSV files and emit publication-friendly tables."""

from __future__ import annotations

import csv
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
INPUTS = [
    RESULTS / "leech_full.csv",
    RESULTS / "frodo640_full.csv",
    RESULTS / "frodo976_full.csv",
    RESULTS / "frodo1344_full.csv",
]
OPERATIONS = ("keygen", "encaps", "decaps_valid", "decaps_invalid", "full_cycle")
SCHEMES = (
    "LeechKEM-1",
    "FrodoKEM-640-SHAKE",
    "LeechKEM-2",
    "FrodoKEM-976-SHAKE",
    "LeechKEM-3",
    "FrodoKEM-1344-SHAKE",
)
PAIRS = (
    ("LeechKEM-1", "FrodoKEM-640-SHAKE"),
    ("LeechKEM-2", "FrodoKEM-976-SHAKE"),
    ("LeechKEM-3", "FrodoKEM-1344-SHAKE"),
)


def read_rows() -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    for path in INPUTS:
        if not path.exists():
            raise SystemExit(f"Missing {path.relative_to(ROOT)}; run the benchmark first.")
        with path.open(newline="", encoding="utf-8") as handle:
            rows.extend(csv.DictReader(handle))
    expected = {(scheme, operation) for scheme in SCHEMES for operation in OPERATIONS}
    actual = {(row["scheme"], row["operation"]) for row in rows}
    if actual != expected or len(rows) != len(expected):
        missing = sorted(expected - actual)
        extra = sorted(actual - expected)
        raise SystemExit(f"Unexpected result set; missing={missing}, extra={extra}")
    order = {(scheme, operation): (i, j) for i, scheme in enumerate(SCHEMES)
             for j, operation in enumerate(OPERATIONS)}
    rows.sort(key=lambda row: order[(row["scheme"], row["operation"])])
    return rows


def format_cell(row: dict[str, str]) -> str:
    return f'{float(row["median_ms"]):.3f} ({float(row["p95_ms"]):.3f})'


def latex_name(name: str) -> str:
    return name.replace("FrodoKEM", r"FrodoKEM")


def main() -> None:
    rows = read_rows()
    by_key = {(row["scheme"], row["operation"]): row for row in rows}

    combined = RESULTS / "runtime_results.csv"
    with combined.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)

    md = [
        "# Full KEM runtime results",
        "",
        "Times are milliseconds per operation and shown as median (p95).",
        "",
        "| Scheme | KeyGen | Encaps | Decaps valid | Decaps invalid | Full cycle |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for scheme in SCHEMES:
        cells = [format_cell(by_key[(scheme, operation)]) for operation in OPERATIONS]
        md.append(f"| {scheme} | " + " | ".join(cells) + " |")
    md.extend(["", "## Paired median ratios (LeechKEM / FrodoKEM)", "",
               "| Pair | KeyGen | Encaps | Decaps valid | Decaps invalid | Full cycle |",
               "|---|---:|---:|---:|---:|---:|"])
    for leech, frodo in PAIRS:
        ratios = []
        for operation in OPERATIONS:
            numerator = float(by_key[(leech, operation)]["median_ms"])
            denominator = float(by_key[(frodo, operation)]["median_ms"])
            ratios.append(f"{numerator / denominator:.2f}x")
        md.append(f"| {leech} / {frodo} | " + " | ".join(ratios) + " |")
    (RESULTS / "runtime_results.md").write_text("\n".join(md) + "\n", encoding="utf-8")

    tex = [
        r"% Generated by tools/merge_results.py. Values: median (p95), ms.",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Scalar reference-implementation runtime over independent "
        r"test cases. Values are median (95th percentile) in milliseconds; "
        r"Full cycle denotes KeyGen, Encaps, and valid Decaps.}",
        r"\label{tab:kem-runtime}",
        r"\begin{tabular}{lrrrrr}",
        r"\toprule",
        r"Scheme & KeyGen & Encaps & Decaps (valid) & Decaps (invalid) & Full cycle \\",
        r"\midrule",
    ]
    for index, scheme in enumerate(SCHEMES):
        cells = [format_cell(by_key[(scheme, operation)]) for operation in OPERATIONS]
        tex.append(latex_name(scheme) + " & " + " & ".join(cells) + r" \\")
        if index in (1, 3):
            tex.append(r"\addlinespace")
    tex.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}", ""])
    (RESULTS / "runtime_results.tex").write_text("\n".join(tex), encoding="utf-8")

    ratios_tex = [
        r"% Generated by tools/merge_results.py. Ratio > 1 means LeechKEM is slower.",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{Paired median-runtime ratios (LeechKEM/FrodoKEM).}",
        r"\label{tab:kem-runtime-ratios}",
        r"\begin{tabular}{lrrrrr}",
        r"\toprule",
        r"Pair & KeyGen & Encaps & Decaps (valid) & Decaps (invalid) & Full cycle \\",
        r"\midrule",
    ]
    for leech, frodo in PAIRS:
        values = []
        for operation in OPERATIONS:
            numerator = float(by_key[(leech, operation)]["median_ms"])
            denominator = float(by_key[(frodo, operation)]["median_ms"])
            values.append(f"{numerator / denominator:.2f}")
        ratios_tex.append(f"{leech}/{frodo} & " + " & ".join(values) + r" \\")
    ratios_tex.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}", ""])
    (RESULTS / "runtime_ratios.tex").write_text("\n".join(ratios_tex), encoding="utf-8")

    print(f"Merged {len(rows)} rows into {combined.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
